            <section class="edx-section" aria-labelledby="causas">
                <h2 id="causas">¿Por qué se abomba la pintura de una fachada?</h2>
                <p>El abolsamiento o ampollamiento de la pintura es una de las patologías más frecuentes en las fachadas de edificios con cubiertas planas con petos. El agua entra en el muro por la coronación del peto, por los anclajes de pérgolas o por filtraciones de la cubierta. Cuando el sol calienta el paramento, esa humedad intenta salir en forma de vapor. Si la fachada está acabada con una pintura plástica de baja transpirabilidad, el vapor queda atrapado bajo la película, que pierde adherencia y forma bolsas, ampollas y desconchados.</p>
                <p>Con el tiempo aparecen también eflorescencias salinas, manchas oscuras de moho y la disgregación del enfoscado.</p>
                <figure class="edx-joint-photo" tabindex="0">
                    <img src="/assets/img/patologia-ampollamiento-pintura-fachada-marbella.webp" width="1280" height="720" loading="lazy" decoding="async" alt="Fachada con abolsamiento de pintura, desconchados y manchas bajo el peto de una terraza">
                    <figcaption>Abolsamiento, desconchados y manchas visibles en el revestimiento de una fachada bajo el peto.</figcaption>
                </figure>
                <p>El origen de la humedad y el estado del soporte deben comprobarse en cada edificio; una fotografía por sí sola no confirma la causa de la lesión.</p>
            </section>
            <section class="edx-section" aria-labelledby="reparacion">
                <h2 id="reparacion">Repintar no soluciona el problema</h2>
                <p>Si se repinta sin eliminar el origen de la humedad, las ampollas vuelven a aparecer en pocos meses. Para una reparación duradera hay que:</p>
                <ol class="edx-repair-steps">
                    <li>Localizar y corregir la entrada de agua: albardillas, goterones, sellado de anclajes e impermeabilización de cubiertas y terrazas.</li>
                    <li>Retirar toda la pintura ampollada y el enfoscado suelto.</li>
                    <li>Tratar sales y moho y dejar secar el soporte.</li>
                    <li>Acabar con un revestimiento transpirable, como pintura al silicato o al siloxano.</li>
                </ol>
            </section>
