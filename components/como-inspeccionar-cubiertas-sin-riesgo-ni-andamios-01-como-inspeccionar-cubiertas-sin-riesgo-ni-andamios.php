				<h1 itemprop="headline">Cómo inspeccionar cubiertas sin riesgo ni andamios</h1>
				<p class="edx-intro-text">
					La cubierta es la parte del edificio que más problemas oculta y la más difícil de inspeccionar.
					Acceder a ella con métodos tradicionales implica andamios, riesgo para operarios y un coste elevado.
					Existe una alternativa más eficiente: los drones operados por técnicos cualificados.
				</p>
