			<div itemprop="articleBody">
				<section class="edx-section">
					<h2>Problemas habituales en cubiertas</h2>
					<p>
						Las cubiertas están sometidas a una exposición constante a la intemperie. Con el tiempo,
						cualquier edificio —independientemente de su edad o construcción— puede desarrollar patologías
						que, si no se detectan a tiempo, derivan en daños estructurales graves y costosas reparaciones.
					</p>
					<p>Los problemas más frecuentes son:</p>
					<ul class="edx-list">
						<li>
							<strong>Filtraciones de agua.</strong>
							El punto de entrada más común. Una junta deteriorada, una grieta mínima o un desagüe
							obstruido puede provocar humedades que afectan a forjados, fachadas e instalaciones
							interiores.
						</li>
						<li>
							<strong>Fallos de impermeabilización.</strong>
							La lámina impermeabilizante se degrada con el tiempo por la radiación UV, las variaciones
							térmicas y el peso acumulado. Cuando falla, el agua penetra sin señales visibles hasta que
							el daño ya es extenso.
						</li>
						<li>
							<strong>Desgaste y envejecimiento de materiales.</strong>
							Tejas desplazadas, chapas oxidadas, membranas agrietadas o grava dispersa son signos
							habituales en cubiertas que llevan años sin revisión.
						</li>
						<li>
							<strong>Vegetación no controlada.</strong>
							La presencia de musgo, líquenes o plantas espontáneas retiene humedad y acelera el deterioro
							de cualquier tipo de cubierta.
						</li>
						<li>
							<strong>Deficiencias en sumideros y canalones.</strong>
							La acumulación de residuos obstruye el drenaje y genera balsas de agua que sobrecargan la
							estructura y favorecen la filtración.
						</li>
					</ul>
					<div class="edx-highlight">
						"Muchas cubiertas llevan años con problemas activos que nadie ha detectado porque nadie ha
						subido a mirarlas."
					</div>
				</section>
				<div class="edx-divider"></div>
				<section class="edx-section">
					<h2>Por qué es difícil inspeccionarlas</h2>
					<p>
						La inspección de cubiertas plantea una serie de barreras que explican por qué muchos edificios
						llegan a situaciones de deterioro avanzado antes de ser revisados:
					</p>
					<ul class="edx-list">
						<li>
							<strong>Acceso complicado.</strong>
							La mayoría de cubiertas no tienen acceso directo o seguro desde el interior del edificio.
							Llegar a ellas requiere montaje de andamios, alquiler de plataformas elevadoras o trabajos
							en altura con medidas de seguridad específicas.
						</li>
						<li>
							<strong>Coste elevado.</strong>
							Un andamio para un edificio de cinco plantas en una calle estrecha de Madrid puede superar
							los 3.000–5.000€ solo en montaje y alquiler, antes de realizar ningún trabajo.
						</li>
						<li>
							<strong>Riesgo para los operarios.</strong>
							Los trabajos en cubierta son una de las principales causas de accidente laboral grave en el
							sector de la construcción. La normativa obliga a medidas que encarecen y ralentizan
							cualquier intervención.
						</li>
						<li>
							<strong>Visibilidad parcial.</strong>
							Incluso cuando se accede físicamente, hay zonas de difícil acceso —limahoyas, juntas
							perimetrales, encuentros con instalaciones— que quedan fuera del campo de visión del
							inspector.
						</li>
						<li>
							<strong>Frecuencia insuficiente.</strong>
							Por todo lo anterior, las inspecciones se posponen sistemáticamente. El resultado es que los
							problemas se detectan cuando ya son urgentes.
						</li>
					</ul>
				</section>
				<div class="edx-divider"></div>
				<section class="edx-section">
					<h2>Cómo se inspeccionan con drones</h2>
					<p>
						La inspección de cubiertas con drones resuelve todos los problemas anteriores sin renunciar al
						rigor técnico. El proceso es el siguiente:
					</p>
					<ul class="edx-list">
						<li>
							<strong>Vuelo de reconocimiento y planificación.</strong>
							Antes de volar, el técnico planifica la inspección según la geometría de la cubierta, las
							condiciones de vuelo y las zonas de mayor riesgo.
						</li>
						<li>
							<strong>Captura de imagen de alta resolución.</strong>
							El dron recorre la cubierta sistemáticamente, capturando imágenes en detalle de todas las
							superficies, juntas, sumideros, encuentros y elementos singulares.
						</li>
						<li>
							<strong>Termografía infrarroja.</strong>
							Combinada con la inspección visual, la cámara termográfica detecta humedad oculta, zonas de
							filtración activa y fallos de impermeabilización que no son visibles a simple vista.
						</li>
						<li>
							<strong>Fotogrametría 3D.</strong>
							En casos que lo requieren, se genera un modelo tridimensional de la cubierta con mediciones
							precisas para planificar intervenciones o comparar el estado en diferentes revisiones.
						</li>
						<li>
							<strong>Análisis e informe técnico.</strong>
							Las imágenes son interpretadas por arquitectos o ingenieros colegiados, que emiten un
							informe con la localización de las patologías, su severidad y las recomendaciones de
							actuación.
						</li>
					</ul>
					<div class="edx-highlight">
						"El dron no es el servicio. Es la herramienta. Lo que marca la diferencia es quién interpreta lo
						que captura."
					</div>
				</section>
