<span class="mono-label-accent">PAT-03 · Puentes térmicos y anomalías</span>
<h1 class="mt-5 heading-display text-3xl md:text-4xl lg:text-5xl text-balance">Puentes térmicos y anomalías térmicas</h1>
<p class="mt-5 text-lg text-muted-foreground leading-relaxed text-pretty">Discontinuidades en el aislamiento de la envolvente que generan pérdidas de energía y riesgo de condensaciones. La termografía las hace visibles como contrastes de temperatura.</p>
</div>
