</div>
<h2 class="mt-4 heading-display text-3xl md:text-4xl lg:text-5xl text-balance text-foreground">Definición técnica</h2>
</div>
<p class="mt-6 text-base md:text-lg text-muted-foreground leading-relaxed text-pretty">Un puente térmico es una zona de la envolvente donde la resistencia térmica se ve reducida por una discontinuidad del aislamiento: encuentros con forjados, marcos, esquinas o zonas donde el aislamiento falta o está degradado. En el termograma aparecen como áreas con temperatura superficial distinta a la del entorno. Su identificación es clave en auditorías energéticas, en el estudio de condensaciones y en la verificación de rehabilitaciones.</p>
