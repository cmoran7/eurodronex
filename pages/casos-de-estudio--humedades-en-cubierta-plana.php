<span class="font-mono text-[11px] uppercase tracking-[0.18em] text-primary pt-1.5">FASE 01</span>
<h3 class="heading-display text-lg md:text-xl pt-1">Problema</h3>
<div>
<p class="text-base text-muted-foreground leading-relaxed">Humeades reiteradas en la última planta con origen indeterminado. La cubierta presenta zonas de encharcamiento junto a sumideros que no permiten descartar fallos de estanqueidad ocultos bajo la impermeabilización.</p>
</div>
</div>
