<h3 class="heading-display text-lg md:text-xl pt-1">Metodología</h3>
<div>
<p class="text-base text-muted-foreground leading-relaxed">Doble captura RGB + térmica en condiciones de diferencial térmico, en las primeras horas de la mañana para maximizar el contraste entre zonas húmedas y secas.</p>
