<span class="font-mono text-[11px] uppercase tracking-[0.18em] text-primary pt-1.5">FASE 02</span>
<h3 class="heading-display text-lg md:text-xl pt-1">Necesidad de inspección</h3>
<div>
<p class="text-base text-muted-foreground leading-relaxed">Delimitar la extensión real de las acumulaciones de agua y detectar anomalías de estanqueidad no visibles, sin sondeos ni intervención destructiva previa.</p>
</div>
</div>
<div class="grid grid-cols-1 md:grid-cols-[90px_240px_1fr] gap-2 md:gap-8 py-8 border-b border-border rise-in" style="animation-delay:120ms">
